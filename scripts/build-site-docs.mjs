// Turns docs/guide.md into site/docs/index.html. Run before deploying the site:
//   node scripts/build-site-docs.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Marked } from 'marked';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = 'https://github.com/umarbashirr/Conn';
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const md = readFileSync(join(root, 'docs/guide.md'), 'utf8');

const slug = (s) => s.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const toc = [];

const marked = new Marked({
  gfm: true,
  renderer: {
    heading({ tokens, depth }) {
      const html = this.parser.parseInline(tokens);
      const id = slug(html);
      if (depth === 2) toc.push({ id, html });
      if (depth === 1) return `<h1>${html}</h1>\n`;
      return `<h${depth} id="${id}"><a class="anchor" href="#${id}" aria-hidden="true">#</a>${html}</h${depth}>\n`;
    },
    link({ href, title, tokens }) {
      const text = this.parser.parseInline(tokens);
      let url = href;
      if (url === '../README.md') url = `${repo}#readme`;
      else if (!/^(https?:|#|mailto:)/.test(url)) url = `${repo}/blob/main/docs/${url}`;
      const ext = /^https?:/.test(url) && !url.startsWith('https://getconn.netlify.app');
      return `<a href="${esc(url)}"${title ? ` title="${esc(title)}"` : ''}${ext ? ' rel="noopener"' : ''}>${text}</a>`;
    },
    image({ href, text }) {
      const src = /^https?:/.test(href) ? href : `https://raw.githubusercontent.com/umarbashirr/Conn/main/docs/${href}`;
      return `<img src="${esc(src)}" alt="${esc(text)}" loading="lazy" />`;
    },
  },
});

const body = marked.parse(md);
const nav = toc.map((t) => `          <li><a href="#${t.id}">${t.html}</a></li>`).join('\n');

const page = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Docs: the Conn guide</title>
    <meta name="description" content="Everything Conn does, in detail: install, the agent panel, the browser, worktrees, skills and MCP, the terminal, the conn CLI and keys." />
    <meta name="color-scheme" content="dark" />
    <meta name="theme-color" content="#08090A" />
    <link rel="icon" href="../favicon.png" />
    <meta property="og:title" content="Docs: the Conn guide" />
    <meta property="og:image" content="https://getconn.netlify.app/og.png" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" />
    <link rel="stylesheet" href="docs.css" />
  </head>
  <body>
    <!-- Generated by scripts/build-site-docs.mjs from docs/guide.md. Edit the guide, not this file. -->
    <a class="skip" href="#doc">Skip to the guide</a>
    <header class="top">
      <div class="top-in">
        <a class="brand" href="../">Conn</a>
        <span class="crumb">Docs</span>
        <span class="ver">v${version}</span>
        <nav class="top-links" aria-label="Site">
          <a href="../">Home</a>
          <a href="${repo}">GitHub</a>
          <a class="dl" href="../#download">Download</a>
        </nav>
      </div>
    </header>
    <div class="layout">
      <aside class="side" aria-label="On this page">
        <details class="toc" open>
          <summary>On this page</summary>
          <ol>
${nav}
          </ol>
        </details>
      </aside>
      <main id="doc" class="doc">
${body}
        <footer class="doc-foot">
          <a href="${repo}/edit/main/docs/guide.md">Edit this page on GitHub</a>
        </footer>
      </main>
    </div>
    <script>
      // Highlight the section in view in the sidebar.
      const links = new Map([...document.querySelectorAll('.toc a')].map((a) => [a.hash.slice(1), a]));
      const io = new IntersectionObserver((es) => {
        for (const e of es) if (e.isIntersecting) {
          links.forEach((a) => a.removeAttribute('aria-current'));
          links.get(e.target.id)?.setAttribute('aria-current', 'true');
        }
      }, { rootMargin: '-70px 0px -75% 0px' });
      document.querySelectorAll('.doc h2[id]').forEach((h) => io.observe(h));
      if (matchMedia('(max-width: 900px)').matches) document.querySelector('.toc').open = false;
    </script>
  </body>
</html>
`;

mkdirSync(join(root, 'site/docs'), { recursive: true });
writeFileSync(join(root, 'site/docs/index.html'), page);
console.log(`site/docs/index.html: ${toc.length} sections, v${version}`);
