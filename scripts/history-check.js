'use strict';
/* The rail lists a chat only when history.js finds what the person first typed
   near the top of its transcript. This writes transcripts shaped like the ones
   the claude binary leaves behind, on a throwaway HOME, and holds which of them
   the rail lists and under what title. */
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'conn-history-'));
process.env.HOME = home;
process.env.USERPROFILE = home;

const failures = [];
const check = (name, ok, detail) => {
  console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : `: ${detail}`}`);
  if (!ok) failures.push(name);
};

const history = require(path.join(ROOT, 'src/main/history.js'));

const cwd = path.join(home, 'work', 'my.app');
const dir = path.join(home, '.claude', 'projects', cwd.replace(/[/.]/g, '-'));
fs.mkdirSync(dir, { recursive: true });

const SESSION = 'abcd1234-0000-4000-8000-';
let n = 0;
const write = (lines) => {
  const id = `${SESSION}${String(++n).padStart(12, '0')}`;
  fs.writeFileSync(path.join(dir, `${id}.jsonl`), lines.map((o) => JSON.stringify(o)).join('\n') + '\n');
  return id;
};

const queued = () => ({ type: 'queue-operation', operation: 'enqueue', timestamp: '2026-10-15T10:00:00.000Z', sessionId: 's' });
const attachment = (size = 400) => ({ type: 'attachment', attachment: { type: 'skill_listing', content: 'x'.repeat(size) }, cwd });
const user = (content, extra) => ({ type: 'user', message: { role: 'user', content }, cwd, ...extra });
const clear = () => user('<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>');

const plain = write([queued(), user('fix the login redirect loop'), { type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text: 'ok' }] } }]);

const IMAGE_TYPED = 'see the issue in the sidebar, the chat list is cut off';
const imageLine = user([
  { type: 'image', source: { type: 'base64', media_type: 'image/png', data: crypto.randomBytes(210000).toString('base64') } },
  { type: 'text', text: `[attached image] image.png\n  file: /tmp/conn-paste-1.png\n\n${IMAGE_TYPED}` },
]);
const imageFirst = write([queued(), queued(), attachment(), attachment(), imageLine]);

const COMMAND_ARGS = "Let's prototype the better UI UX for the rail";
const slashFirst = write([
  queued(),
  user(`<command-message>pstack:poteto-mode</command-message>\n<command-name>/pstack:poteto-mode</command-name>\n<command-args>  ${COMMAND_ARGS}\n</command-args>`),
  user([{ type: 'text', text: 'Base directory for this skill: /home/x/.claude/skills/poteto-mode' }], { isMeta: true }),
  ...Array.from({ length: 40 }, () => attachment(4000)),
  user('a later prompt that starts past the budget'),
]);

const afterClear = write([
  user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', { isMeta: true }),
  clear(),
  user('why is the swagger page blank'),
]);

const bareSkill = write([queued(), user('<command-message>caveman-setup</command-message>\n<command-name>/caveman-setup</command-name>\n<command-args></command-args>')]);

const empty = write([queued(), queued(), queued()]);

const lineBytes = Buffer.byteLength(JSON.stringify(imageLine));
const laterAt = fs.readFileSync(path.join(dir, `${slashFirst}.jsonl`), 'utf8').indexOf('a later prompt');
check('fixture-image-line-is-over-200kb', lineBytes > 200 * 1024, `${lineBytes} bytes`);
check('fixture-later-prompt-starts-past-128kb', laterAt > 1 << 17, `starts at ${laterAt}`);

const rows = history.listSessions(cwd);
const titleFor = (id) => rows.find((r) => r.id === id)?.title;
const expect = (name, id, want) => check(name, titleFor(id) === want, `title ${JSON.stringify(titleFor(id))}, want ${JSON.stringify(want)}`);

expect('plain-typed-chat-is-listed-with-what-was-typed', plain, 'fix the login redirect loop');
expect('image-first-chat-is-listed-with-the-text-typed-under-the-image', imageFirst, IMAGE_TYPED);
expect('slash-command-chat-is-listed-with-the-command-as-typed', slashFirst, `/pstack:poteto-mode ${COMMAND_ARGS}`);
expect('chat-started-by-clear-is-listed-with-the-prompt-typed-after-it', afterClear, 'why is the swagger page blank');
expect('chat-with-only-a-bare-command-is-listed-with-the-command', bareSkill, '/caveman-setup');
check('chat-with-nothing-typed-is-hidden', titleFor(empty) === undefined, `listed as ${JSON.stringify(titleFor(empty))}`);

const live = write([clear()]);
check('live-chat-caught-at-its-clear-line-lists-as-clear-for-now', history.listSessions(cwd).find((r) => r.id === live)?.title === '/clear', 'not listed as /clear');
fs.appendFileSync(path.join(dir, `${live}.jsonl`), JSON.stringify(user('now the real question')) + '\n');
check('live-chat-retitled-once-the-prompt-lands', history.listSessions(cwd).find((r) => r.id === live)?.title === 'now the real question',
  JSON.stringify(history.listSessions(cwd).find((r) => r.id === live)?.title));

// projectDir falls back to reading the cwd out of a transcript when the slug
// rule misses, and that read goes through the same head parser.
const other = path.join(home, 'elsewhere');
const odd = path.join(home, '.claude', 'projects', 'not-the-slug');
fs.mkdirSync(odd, { recursive: true });
fs.writeFileSync(path.join(odd, `${SESSION}999999999999.jsonl`), JSON.stringify(queued()) + '\n' + JSON.stringify(user('hi', { cwd: other })) + '\n');
check('project-folder-found-by-recorded-cwd', history.projectDir(other) === odd, history.projectDir(other));

fs.rmSync(home, { recursive: true, force: true });
console.log(failures.length ? `\n${failures.length} failed` : '\nall passed');
process.exit(failures.length ? 1 : 0);
